export async function getAutomationConfig(): Promise<AutomationConfig> {
  const db = getFirestoreDb();
  if (db) {
    try {
      const doc = await db.collection('automation').doc('config').get();
      if (doc.exists) {
        const data = doc.data() as Partial<AutomationConfig>;
        const resolvedDevtoQueue = Array.isArray(data.devtoTopicsQueue)
          ? data.devtoTopicsQueue
          : Array.isArray(data.topicsQueue)
          ? data.topicsQueue
          : DEFAULT_AUTOMATION_CONFIG.devtoTopicsQueue;
        const resolvedLinkedinQueue = Array.isArray(data.linkedinTopicsQueue)
          ? data.linkedinTopicsQueue
          : DEFAULT_AUTOMATION_CONFIG.linkedinTopicsQueue;
        return {
          ...DEFAULT_AUTOMATION_CONFIG,
          ...data,
          devtoTopicsQueue: resolvedDevtoQueue,
          topicsQueue: resolvedDevtoQueue,
          linkedinTopicsQueue: resolvedLinkedinQueue,
          linkedinTopicImages: data.linkedinTopicImages || {},
          blogSchedule: {
            ...DEFAULT_AUTOMATION_CONFIG.blogSchedule,
            ...(data.blogSchedule || {
              enabled: data.enabled ?? false,
              scheduleMode: data.scheduleMode ?? 'days_of_week',
              daysOfWeek: data.daysOfWeek ?? [1, 4],
              intervalDays: data.intervalDays ?? 3,
              timeOfDay: data.timeOfDay ?? '09:00',
              lastRunAt: data.lastRunAt,
              lastRunStatus: data.lastRunStatus,
            }),
          },
          linkedinSchedule: {
            ...DEFAULT_AUTOMATION_CONFIG.linkedinSchedule,
            ...(data.linkedinSchedule || {}),
          },
          masterPrompts: {
            ...DEFAULT_MASTER_PROMPTS,
            ...(data.masterPrompts || {}),
          },
        };
      }
    } catch (err) {
      console.warn('[automation] Firestore getAutomationConfig fallback:', err);
    }
  }
  return memoryAutomationConfig;
}

export async function saveAutomationConfig(patch: Partial<AutomationConfig>): Promise<AutomationConfig> {
  const current = await getAutomationConfig();
  const nextBlogSchedule: PostTypeSchedule = {
    ...current.blogSchedule,
    ...(patch.blogSchedule || {}),
  };
  const nextLinkedinSchedule: PostTypeSchedule = {
    ...current.linkedinSchedule,
    ...(patch.linkedinSchedule || {}),
  };
  const nextDevtoQueue =
    patch.devtoTopicsQueue !== undefined
      ? patch.devtoTopicsQueue
      : patch.topicsQueue !== undefined
      ? patch.topicsQueue
      : current.devtoTopicsQueue;
  const nextLinkedinQueue =
    patch.linkedinTopicsQueue !== undefined
      ? patch.linkedinTopicsQueue
      : current.linkedinTopicsQueue;

  const updated: AutomationConfig = {
    ...current,
    ...patch,
    devtoTopicsQueue: nextDevtoQueue,
    topicsQueue: nextDevtoQueue,
    linkedinTopicsQueue: nextLinkedinQueue,
    enabled: nextBlogSchedule.enabled || nextLinkedinSchedule.enabled,
    scheduleMode: nextBlogSchedule.scheduleMode,
    daysOfWeek: nextBlogSchedule.daysOfWeek,
    intervalDays: nextBlogSchedule.intervalDays,
    timeOfDay: nextBlogSchedule.timeOfDay,
    blogSchedule: nextBlogSchedule,
    linkedinSchedule: nextLinkedinSchedule,
    masterPrompts: {
      ...current.masterPrompts,
      ...(patch.masterPrompts || {}),
    },
  };
  memoryAutomationConfig = updated;

  const db = getFirestoreDb();
  if (db) {
    await db
      .collection('automation')
      .doc('config')
      .set(JSON.parse(JSON.stringify(updated)), { merge: true });
  }
  return updated;
}

