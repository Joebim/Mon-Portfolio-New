export async function logAutomationStep(
  entry: Omit<AutomationLogEntry, 'id' | 'timestamp'>
): Promise<AutomationLogEntry> {
  const fullEntry: AutomationLogEntry = {
    id: `log-${Date.now()}-${Math.random().toString(36).slice(2, 7)}`,
    timestamp: new Date().toISOString(),
    ...entry,
  };

  const durStr = fullEntry.durationMs !== undefined ? ` (+${fullEntry.durationMs}ms)` : '';
  const metaStr = fullEntry.meta ? ` | meta=${JSON.stringify(fullEntry.meta).slice(0, 600)}` : '';
  const formattedLine = `[Automation:${fullEntry.pipeline.toUpperCase()}][${fullEntry.level.toUpperCase()}][${fullEntry.step}]${durStr} ${fullEntry.message}${metaStr}`;

  if (fullEntry.level === 'error') {
    console.error(formattedLine);
  } else if (fullEntry.level === 'warn') {
    console.warn(formattedLine);
  } else {
    console.log(formattedLine);
  }

  memoryAutomationLogs = [fullEntry, ...memoryAutomationLogs].slice(0, MAX_AUTOMATION_LOGS);

  const db = getFirestoreDb();
  if (db) {
    db.collection('automation')
      .doc('logs')
      .set(
        {
          entries: JSON.parse(JSON.stringify(memoryAutomationLogs.slice(0, 100))),
          updatedAt: fullEntry.timestamp,
        },
        { merge: true }
      )
      .catch((err) => {
        console.warn('[Automation:LOGGER] Firestore log persist warning:', err);
      });
  }

  return fullEntry;
}

export async function getAutomationLogs(): Promise<AutomationLogEntry[]> {
  const db = getFirestoreDb();
  if (db) {
    try {
      const doc = await db.collection('automation').doc('logs').get();
      if (doc.exists) {
        const data = doc.data();
        if (Array.isArray(data?.entries) && data.entries.length > 0) {
          // Merge in-memory and Firestore entries by id, newest first
          const mergedMap = new Map<string, AutomationLogEntry>();
          for (const item of [...memoryAutomationLogs, ...data.entries]) {
            if (item?.id) mergedMap.set(item.id, item);
          }
          const sorted = Array.from(mergedMap.values())
            .sort((a, b) => new Date(b.timestamp).getTime() - new Date(a.timestamp).getTime())
            .slice(0, MAX_AUTOMATION_LOGS);
          memoryAutomationLogs = sorted;
          return sorted;
        }
      }
    } catch (err) {
      console.warn('[Automation:LOGGER] Failed to read Firestore logs:', err);
    }
  }
  return memoryAutomationLogs;
}

export async function clearAutomationLogs(): Promise<void> {
  memoryAutomationLogs = [];
  const db = getFirestoreDb();
  if (db) {
    try {
      await db.collection('automation').doc('logs').set({
        entries: [],
        updatedAt: new Date().toISOString(),
      });
    } catch (err) {
      console.warn('[Automation:LOGGER] Failed to clear Firestore logs:', err);
    }
  }
}

