export async function syncCommentsAndReactions(): Promise<{
  comments: TrackedComment[];
  syncedArticles: number;
}> {
  const { articles } = await getAllBlogArticles();
  const db = getFirestoreDb();
  let syncedArticles = 0;

  for (const article of articles.slice(0, 10)) {
    if (!article.devtoId) continue;
    try {
      const [devtoComments, fullDevTo] = await Promise.all([
        getDevToComments(article.devtoId),
        getArticle(article.devtoId).catch(() => null),
      ]);
      syncedArticles++;

      for (const c of devtoComments.slice(0, 10)) {
        const plainText = (c.body_html || '').replace(/<[^>]+>/g, '').trim();
        if (!plainText) continue;
        const commentId = `devto-${c.id_code}`;
        const item: TrackedComment = {
          id: commentId,
          platform: 'devto',
          articleSlug: article.slug,
          articleTitle: article.title,
          authorName: c.user?.name || c.user?.username || 'Reader',
          authorHandle: c.user?.username ? `@${c.user.username}` : undefined,
          commentText: plainText,
          status: 'pending',
          externalUrl: `${article.devtoUrl || `https://dev.to/joebim/${article.slug}`}#comment-${c.id_code}`,
          createdAt: c.created_at || new Date().toISOString(),
        };
        memoryComments.set(commentId, item);
        if (db) {
          await db.collection('social_comments').doc(commentId).set(JSON.parse(JSON.stringify(item)), { merge: true });
        }
      }

      // Update reaction counts on matching social post if exists
      if (fullDevTo && db) {
        const socialSnap = await db
          .collection('social_posts')
          .where('articleSlug', '==', article.slug)
          .limit(1)
          .get();
        if (!socialSnap.empty) {
          const doc = socialSnap.docs[0];
          const data = doc.data() as SocialPostRecord;
          await doc.ref.update({
            'reactions.devtoReactions': fullDevTo.public_reactions_count || 0,
            'reactions.devtoComments': fullDevTo.comments_count || devtoComments.length,
          });
          memorySocialPosts.set(data.id, {
            ...data,
            reactions: {
              ...data.reactions,
              devtoReactions: fullDevTo.public_reactions_count || 0,
              devtoComments: fullDevTo.comments_count || devtoComments.length,
            },
          });
        }
      }
    } catch (err) {
      console.warn(`[automation] Comment sync skipped for ${article.slug}:`, err);
    }
  }

  const comments = await listTrackedComments();
  return { comments, syncedArticles };
}

