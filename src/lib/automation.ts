export async function runAutomatedBlogPipeline(options: {
  customTopic?: string;
  forcePublish?: boolean;
} = {}): Promise<AutomationRunResult> {
  const pipelineStart = Date.now();
  await logAutomationStep({
    level: 'info',
    pipeline: 'blog',
    step: 'BLOG_PIPELINE_START',
    message: `Starting Automated Blog Pipeline (${options.customTopic ? `customTopic="${options.customTopic}"` : 'weekly DEV.to queue mode'})`,
    meta: { options },
  });

  try {
    // Ensure DEV.to weekly queue is generated for the current week (or replenished if cycle completed)
    const config = options.customTopic?.trim()
      ? await getAutomationConfig()
      : await ensureWeeklyQueuesPopulated('devto');

    // 1. Pick topic from DEV.to weekly queue (`devtoTopicsQueue`)
    let topic = options.customTopic?.trim() || '';
    let remainingDevtoQueue = [...(config.devtoTopicsQueue || config.topicsQueue || [])];
    if (!topic) {
      if (remainingDevtoQueue.length > 0) {
        topic = remainingDevtoQueue.shift()!;
      } else {
        const keyword =
          config.nicheKeywords[Math.floor(Math.random() * config.nicheKeywords.length)] ||
          'Frontend Engineering & TypeScript Architecture';
        topic = `Advanced production engineering guide on ${keyword} (${new Date().toLocaleDateString('en-US', { month: 'short', year: 'numeric' })})`;
      }
    }

    await logAutomationStep({
      level: 'info',
      pipeline: 'blog',
      step: 'STEP_1_TOPIC_SELECTED',
      message: `Selected topic: "${topic}" (${remainingDevtoQueue.length} remaining in this week's DEV.to queue)`,
      meta: { topic, remainingDevtoQueueCount: remainingDevtoQueue.length, remainingDevtoQueue },
    });

    // 2. Generate the blog post via AI using Blog Master Prompt
    const genStart = Date.now();
    const aiRes = await generateTextWithFreeAI(
      config.masterPrompts.blogMasterPrompt,
      `Write a comprehensive, deeply technical blog post on the following topic:
TOPIC: "${topic}"

IMPORTANT OUTPUT FORMAT (use this exact delimiter structure instead of JSON so TypeScript code blocks with braces and quotes are never corrupted):
TITLE: <catchy, specific engineering title>
DESCRIPTION: <1-2 sentence summary (max 160 chars)>
TAGS: <4 comma-separated lowercase alphanumeric tags, e.g. react, typescript, webdev, architecture>
IMAGE_PROMPT: <visual description for a dark-mode 3D/abstract tech cover illustration>
---MARKDOWN---
<full article in clean Markdown with ## headings and code blocks>`,
      config.textModel,
      false
    );

    const { title, description, tags, bodyMarkdown, imagePrompt } = parseGeneratedBlogResponse(
      aiRes.text,
      topic
    );

    if (!bodyMarkdown) {
      throw new Error('AI returned an empty blog markdown body.');
    }

    await logAutomationStep({
      level: 'success',
      pipeline: 'blog',
      step: 'STEP_2_ARTICLE_PARSED',
      message: `Parsed article "${title}" (${bodyMarkdown.length} chars Markdown, tags=[${tags.join(', ')}]) via ${aiRes.modelUsed}`,
      durationMs: Date.now() - genStart,
      meta: {
        title,
        description,
        tags,
        imagePrompt,
        markdownLength: bodyMarkdown.length,
        modelUsed: aiRes.modelUsed,
      },
    });

    // 3. Generate Free AI Cover Image & upload to Cloudinary (tailored to the generated blog title)
    let coverImageUrl: string | undefined;
    if (config.autoGenerateCoverImage) {
      try {
        const imgRes = await generateFreeCoverImage(imagePrompt, {
          blogTitle: title,
          topic,
          description,
          tags,
          articleContent: bodyMarkdown,
          platform: 'DEV.to & Portfolio Blog',
          imageMasterPrompt: config.masterPrompts.imageMasterPrompt,
          model: config.imageModel,
          uploadToCloud: true,
        });
        coverImageUrl = imgRes.devtoCompatibleUrl || imgRes.imageUrl;
      } catch (err) {
        await logAutomationStep({
          level: 'warn',
          pipeline: 'blog',
          step: 'STEP_3_COVER_IMAGE_SKIPPED',
          message: `Cover image generation warning: ${err instanceof Error ? err.message : String(err)}`,
        });
      }
    }

    // 4. Create Blog Article (saves to Firestore + publishes to DEV.to + pulls DEV.to cover image back + updates Hero Featured Post + immediately dispatches newsletter)
    const publishStart = Date.now();
    const isDraft =
      options.forcePublish !== undefined ? !options.forcePublish : !config.autoPublishBlog;
    const created = await createBlogArticle({
      title,
      description,
      bodyMarkdown,
      tagList: tags,
      coverImage: coverImageUrl,
      isDraft,
      publishTo: config.autoPublishDevTo ? ['devto'] : [],
    });

    await logAutomationStep({
      level: created.devto && !created.devto.success ? 'warn' : 'success',
      pipeline: 'blog',
      step: 'STEP_4_PUBLISH_AND_NEWSLETTER',
      message: `Saved blog "${created.article.title}" (slug=${created.article.slug}, draft=${isDraft}, devto=${created.devto?.success ? created.devto.url : created.devto?.error || 'skipped'}, newsletterSent=${created.newsletter?.sentCount ?? 0})`,
      durationMs: Date.now() - publishStart,
      meta: {
        slug: created.article.slug,
        isDraft,
        coverImage: created.article.coverImage,
        devto: created.devto,
        newsletter: created.newsletter,
      },
    });

    // If DEV.to publishing was attempted and failed, send an immediate failure notification message
    if (config.autoPublishDevTo && created.devto && !created.devto.success) {
      await sendAutomationFailureAlert({
        pipeline: 'blog',
        pipelineLabel: 'DEV.to Blog Cross-Posting',
        topicOrTitle: created.article.title,
        failedStep: 'STEP_4_DEVTO_PUBLISH_FAILED',
        errorMessage: `Blog was saved to your portfolio (${created.article.slug}), but DEV.to publishing failed: ${created.devto.error || 'Unknown DEV.to error'}`,
      });
    }

    // 5. LinkedIn runs on its own independent pipeline & schedule (runAutomatedLinkedInPipeline),
    // so RUN BLOG AUTOMATION NOW never cross-posts or leaks partial blog text to LinkedIn.
    const socialPost: SocialPostRecord | undefined = undefined;

    // 6. Newsletter was already dispatched immediately inside createBlogArticle upon publish
    const newsletterResult: AutomationRunResult['newsletterResult'] = created.newsletter;
    const nowIso = new Date().toISOString();

    // 7. Update automation state (pop DEV.to topic queue & record blogSchedule.lastRunAt)
    await saveAutomationConfig({
      devtoTopicsQueue: remainingDevtoQueue,
      topicsQueue: remainingDevtoQueue,
      lastRunAt: nowIso,
      lastRunStatus: `Published "${created.article.title}" (${remainingDevtoQueue.length} left in week's DEV.to queue)`,
      blogSchedule: {
        ...config.blogSchedule,
        lastRunAt: nowIso,
        lastRunStatus: `Published "${created.article.title}" (${remainingDevtoQueue.length} left in week's DEV.to queue)`,
      },
    });

    // If all DEV.to cues for this cycle were just fulfilled, pre-generate the next cycle queue so the queue is never empty
    if (remainingDevtoQueue.length === 0) {
      try {
        await logAutomationStep({
          level: 'info',
          pipeline: 'weekly-queue',
          step: 'DEVTO_QUEUE_CYCLE_REPLENISH',
          message: 'All DEV.to cues for this cycle fulfilled — auto-generating next weekly DEV.to queue.',
        });
        await generateWeeklyQueuesWithAI({ target: 'devto' });
      } catch (err) {
        console.warn('[automation] Auto-replenish DEV.to weekly queue warning:', err);
      }
    }

    await logAutomationStep({
      level: 'success',
      pipeline: 'blog',
      step: 'BLOG_PIPELINE_COMPLETE',
      message: `Completed Automated Blog Pipeline for "${created.article.title}"`,
      durationMs: Date.now() - pipelineStart,
      meta: {
        topicUsed: topic,
        modelUsed: aiRes.modelUsed,
        slug: created.article.slug,
        devtoUrl: created.devto?.url,
        newsletterSentCount: newsletterResult?.sentCount,
      },
    });

    // Notify Admin by email that the automated blog post has been posted
    const siteUrl = (process.env.NEXT_PUBLIC_SITE_URL || 'http://localhost:3000').replace(/\/$/, '');
    await sendAutomationSuccessAlert({
      pipeline: 'blog',
      pipelineLabel: isDraft ? 'Automated Blog Draft Saved' : 'Automated Blog Published',
      title: created.article.title,
      summary: created.article.description,
      liveUrl: `${siteUrl}/blog/${created.article.slug}`,
      devtoUrl: created.devto?.url,
      coverImageUrl: created.article.coverImage,
      modelUsed: aiRes.modelUsed,
      newsletterSentCount: newsletterResult?.sentCount,
      isDraft,
    });

    return {
      success: true,
      topicUsed: topic,
      modelUsed: aiRes.modelUsed,
      article: created.article,
      coverImageUrl: created.article.coverImage,
      devtoResult: created.devto,
      newsletterResult,
      socialPost,
    };
  } catch (error) {
    const errMsg = error instanceof Error ? error.message : String(error);
    const stackSnippet = error instanceof Error ? error.stack?.slice(0, 600) : undefined;

    await logAutomationStep({
      level: 'error',
      pipeline: 'blog',
      step: 'BLOG_PIPELINE_ERROR',
      message: errMsg,
      durationMs: Date.now() - pipelineStart,
      meta: {
        stack: stackSnippet,
      },
    });

    await sendAutomationFailureAlert({
      pipeline: 'blog',
      pipelineLabel: 'DEV.to & Portfolio Blog Automation',
      topicOrTitle: options.customTopic || undefined,
      failedStep: 'BLOG_PIPELINE_ERROR',
      errorMessage: errMsg,
      stackSnippet,
    });

    throw error;
  }
}

