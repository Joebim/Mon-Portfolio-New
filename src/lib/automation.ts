// ---------------------------------------------------------------------------
// Parse JSON & Blog Responses safely from LLM response (immune to truncated JSON or code blocks)
// ---------------------------------------------------------------------------

function closeUnclosedCodeFences(markdown: string): string {
  const fenceMatches = markdown.match(/^```/gm);
  if (fenceMatches && fenceMatches.length % 2 !== 0) {
    return `${markdown.trimEnd()}\n\`\`\`\n`;
  }
  return markdown;
}

function unescapeJsonStringFragment(fragment: string): string {
  return fragment
    .replace(/\\n/g, '\n')
    .replace(/\\r/g, '\r')
    .replace(/\\t/g, '\t')
    .replace(/\\"/g, '"')
    .replace(/\\\\/g, '\\');
}

function extractJsonObject(raw: string): any {
  const cleaned = raw
    .replace(/^```json\s*/i, '')
    .replace(/^```\s*/i, '')
    .replace(/\s*```$/, '')
    .trim();

  try {
    return JSON.parse(cleaned);
  } catch {
    // 1. Try slicing from first '{' to last '}'
    const start = cleaned.indexOf('{');
    const end = cleaned.lastIndexOf('}');
    if (start !== -1 && end > start) {
      const candidate = cleaned.slice(start, end + 1);
      try {
        return JSON.parse(candidate);
      } catch {
        // Continue to repair attempt
      }
    }

    // 2. Try repairing truncated JSON string (e.g. "Unterminated string in JSON")
    if (start !== -1) {
      const fragment = cleaned.slice(start);
      for (const suffix of ['"}', '"\n}', '"]}']) {
        try {
          return JSON.parse(fragment + suffix);
        } catch {
          // try next suffix
        }
      }
    }

    // 3. Field-by-field regex extraction fallback for blog/JSON payloads
    const titleMatch = cleaned.match(/"title"\s*:\s*"((?:[^"\\]|\\.)*)"/);
    const descMatch = cleaned.match(/"description"\s*:\s*"((?:[^"\\]|\\.)*)"/);
    const imgMatch = cleaned.match(/"imagePrompt"\s*:\s*"((?:[^"\\]|\\.)*)"/);
    const tagsMatch = cleaned.match(/"tags"\s*:\s*\[([\s\S]*?)\]/);
    const bodyKeyMatch = cleaned.match(/"(?:bodyMarkdown|body)"\s*:\s*"/);

    if (titleMatch || bodyKeyMatch) {
      let bodyMarkdown = '';
      if (bodyKeyMatch && bodyKeyMatch.index !== undefined) {
        let rawBody = cleaned.slice(bodyKeyMatch.index + bodyKeyMatch[0].length);
        // Strip trailing JSON close like `"}` or `"\n}`
        rawBody = rawBody.replace(/"\s*,?\s*\}\s*$/, '').replace(/"\s*$/, '');
        bodyMarkdown = closeUnclosedCodeFences(unescapeJsonStringFragment(rawBody).trim());
      }

      const tags = tagsMatch
        ? tagsMatch[1]
            .split(',')
            .map((t) => t.replace(/["'\s]/g, '').toLowerCase().replace(/[^a-z0-9]/g, ''))
            .filter(Boolean)
            .slice(0, 4)
        : undefined;

      return {
        title: titleMatch ? unescapeJsonStringFragment(titleMatch[1]) : undefined,
        description: descMatch ? unescapeJsonStringFragment(descMatch[1]) : undefined,
        imagePrompt: imgMatch ? unescapeJsonStringFragment(imgMatch[1]) : undefined,
        tags,
        bodyMarkdown,
      };
    }

    throw new Error('Failed to parse structured JSON from AI model response.');
  }
}

function parseGeneratedBlogResponse(
  raw: string,
  fallbackTopic: string
): {
  title: string;
  description: string;
  tags: string[];
  imagePrompt: string;
  bodyMarkdown: string;
} {
  const cleaned = raw
    .replace(/^```(?:markdown|md|json)?\s*/i, '')
    .replace(/\s*```$/, '')
    .trim();

  // 1. Check for delimiter format: ---MARKDOWN--- or ---BODY_MARKDOWN---
  const delimiterMatch = cleaned.match(/\n---+(?:BODY_)?MARKDOWN---+\s*\n/i);
  if (delimiterMatch && delimiterMatch.index !== undefined) {
    const headerPart = cleaned.slice(0, delimiterMatch.index);
    let bodyPart = cleaned.slice(delimiterMatch.index + delimiterMatch[0].length).trim();

    const extractHeader = (key: string): string => {
      const regex = new RegExp(`^\\s*(?:\\*\\*)?${key}(?:\\*\\*)?\\s*:\\s*(.+)$`, 'im');
      const m = headerPart.match(regex);
      return m ? m[1].trim().replace(/^["']|["']$/g, '') : '';
    };

    const title = extractHeader('TITLE') || fallbackTopic;
    const description =
      extractHeader('DESCRIPTION') || `Practical engineering deep dive into ${title}.`;
    const rawTags = extractHeader('TAGS');
    const tags = rawTags
      ? rawTags
          .replace(/^\[|\]$/g, '')
          .split(/[,\s]+/)
          .map((t) => t.toLowerCase().replace(/[^a-z0-9]/g, ''))
          .filter(Boolean)
          .slice(0, 4)
      : ['typescript', 'react', 'webdev', 'architecture'];
    const imagePrompt = extractHeader('IMAGE_PROMPT') || title;

    // Remove duplicate H1 at top of body if model included it
    bodyPart = bodyPart.replace(/^#\s+.+\n+/, '').trim();

    return {
      title,
      description,
      tags: tags.length > 0 ? tags : ['typescript', 'react', 'webdev', 'architecture'],
      imagePrompt,
      bodyMarkdown: closeUnclosedCodeFences(bodyPart),
    };
  }

  // 2. If response looks like JSON (starts with '{' or contains `"bodyMarkdown"`), use resilient JSON extractor
  if (cleaned.startsWith('{') || cleaned.includes('"bodyMarkdown"')) {
    const generated = extractJsonObject(cleaned);
    const title = String(generated.title || fallbackTopic).trim();
    const description = String(
      generated.description || `Practical engineering deep dive into ${title}.`
    ).trim();
    const tags: string[] = Array.isArray(generated.tags)
      ? generated.tags
          .map((t: any) => String(t).toLowerCase().replace(/[^a-z0-9]/g, ''))
          .filter(Boolean)
          .slice(0, 4)
      : ['typescript', 'react', 'webdev', 'architecture'];
    const bodyMarkdown = closeUnclosedCodeFences(
      String(generated.bodyMarkdown || generated.body || '').trim()
    );
    const imagePrompt = String(generated.imagePrompt || title).trim();

    if (bodyMarkdown) {
      return {
        title,
        description,
        tags: tags.length > 0 ? tags : ['typescript', 'react', 'webdev', 'architecture'],
        imagePrompt,
        bodyMarkdown,
      };
    }
  }

  // 3. Fallback: Plain Markdown response without delimiter
  let bodyPart = cleaned;
  let title = fallbackTopic;
  const h1Match = bodyPart.match(/^#\s+(.+)$/m);
  if (h1Match) {
    title = h1Match[1].trim();
    bodyPart = bodyPart.replace(/^#\s+.+\n*/, '').trim();
  }

  return {
    title,
    description: `Practical engineering deep dive into ${title}.`,
    tags: ['typescript', 'react', 'webdev', 'architecture'],
    imagePrompt: title,
    bodyMarkdown: closeUnclosedCodeFences(bodyPart),
  };
}

