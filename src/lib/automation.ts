/**
 * Returns the Monday date string (YYYY-MM-DD) representing the start of the current week.
 */
export function getStartOfWeekKey(now = new Date()): string {
  const d = new Date(now);
  const day = d.getDay(); // 0 (Sun) - 6 (Sat)
  // Shift to Monday of the current week
  const diffToMonday = day === 0 ? -6 : 1 - day;
  d.setDate(d.getDate() + diffToMonday);
  return d.toISOString().slice(0, 10);
}

/**
 * Calculates how many posts are scheduled in a 7-day week for a given PostTypeSchedule.
 */
export function calculateWeeklyPostCount(schedule: PostTypeSchedule): number {
  if (!schedule) return 2;
  if (schedule.scheduleMode === 'interval_days') {
    const interval = Math.max(1, schedule.intervalDays || 3);
    return Math.max(1, Math.min(7, Math.ceil(7 / interval)));
  }
  const count = Array.isArray(schedule.daysOfWeek) ? schedule.daysOfWeek.length : 0;
  return Math.max(1, Math.min(7, count || 2));
}

const DAY_NAMES = ['Sunday', 'Monday', 'Tuesday', 'Wednesday', 'Thursday', 'Friday', 'Saturday'];

function parseTopicLines(sectionText: string, expectedCount: number, fallbackKeywords: string[], prefixLabel: string): string[] {
  const lines = sectionText
    .split('\n')
    .map((line) =>
      line
        .replace(/^\s*[-*•]\s*/, '')
        .replace(/^\s*\d+[.)]\s*/, '')
        .replace(/^["']|["']$/g, '')
        .trim()
    )
    .filter((line) => line.length >= 10 && !line.startsWith('---') && !/^(DEVTO|LINKEDIN)_QUEUE/i.test(line));

  const results = lines.slice(0, expectedCount);
  while (results.length < expectedCount) {
    const kw =
      fallbackKeywords[results.length % Math.max(1, fallbackKeywords.length)] ||
      'Frontend Architecture & TypeScript';
    results.push(`${prefixLabel}: Production Engineering Patterns in ${kw} (Slot #${results.length + 1})`);
  }
  return results;
}

/**
 * Uses AI to auto-generate the weekly topic queues separately for:
 *  - DEV.to & Portfolio Blog (`devtoTopicsQueue`), sized to `blogSchedule` posting days per week
 *  - LinkedIn Official Posts (`linkedinTopicsQueue`), sized to `linkedinSchedule` posting days per week
 */
export async function generateWeeklyQueuesWithAI(options: {
  target?: 'both' | 'devto' | 'linkedin';
} = {}): Promise<{
  config: AutomationConfig;
  devtoGenerated: string[];
  linkedinGenerated: string[];
  devtoCount: number;
  linkedinCount: number;
  weekKey: string;
  modelUsed: string;
}> {
  const target = options.target || 'both';
  const config = await getAutomationConfig();
  const weekKey = getStartOfWeekKey();
  const devtoCount = calculateWeeklyPostCount(config.blogSchedule);
  const linkedinCount = calculateWeeklyPostCount(config.linkedinSchedule);
  const queueStart = Date.now();

  await logAutomationStep({
    level: 'info',
    pipeline: 'weekly-queue',
    step: 'WEEKLY_QUEUE_GEN_START',
    message: `Generating weekly queues for week of ${weekKey} (target=${target}, devtoSlots=${devtoCount}, linkedinSlots=${linkedinCount})`,
    meta: {
      target,
      weekKey,
      devtoCount,
      linkedinCount,
      blogDaysOfWeek: config.blogSchedule.daysOfWeek,
      linkedinDaysOfWeek: config.linkedinSchedule.daysOfWeek,
    },
  });

  const devtoDayLabels =
    config.blogSchedule.scheduleMode === 'days_of_week' && config.blogSchedule.daysOfWeek.length > 0
      ? config.blogSchedule.daysOfWeek.map((d) => DAY_NAMES[d] || `Day ${d}`).join(', ')
      : `${devtoCount} days this week`;

  const linkedinDayLabels =
    config.linkedinSchedule.scheduleMode === 'days_of_week' && config.linkedinSchedule.daysOfWeek.length > 0
      ? config.linkedinSchedule.daysOfWeek.map((d) => DAY_NAMES[d] || `Day ${d}`).join(', ')
      : `${linkedinCount} days this week`;

  let existingTitles: string[] = [];
  try {
    const { articles } = await getAllBlogArticles();
    existingTitles = articles.slice(0, 15).map((a) => a.title);
  } catch {
    // ignore
  }

  const pillars =
    config.nicheKeywords.length > 0
      ? config.nicheKeywords.join(', ')
      : 'Frontend Architecture, Financial Tooling & Fintech UX, TypeScript Design Patterns, React 19 & Next.js Performance';

  const systemPrompt = `You are the Editorial & Content Strategy Engine for Joseph Akinwole (Senior Frontend & Full-Stack Engineer specializing in React, Next.js, TypeScript, Angular, and Fintech systems).
Your job is to plan the weekly content queues separately for DEV.to technical blog articles and LinkedIn executive engineering posts.`;

  const userPrompt = `Generate this week's content queues (Week starting ${weekKey}) based on these Niche Pillars:
NICHE PILLARS: ${pillars}
${existingTitles.length > 0 ? `AVOID REPEATING THESE RECENTLY PUBLISHED TITLES:\n- ${existingTitles.join('\n- ')}\n` : ''}

SCHEDULE REQUIREMENTS FOR THIS WEEK:
1. DEV.to Blog Queue: Exactly ${devtoCount} deep-dive technical blog topic(s) for scheduled days (${devtoDayLabels}). Focus on concrete architecture, code patterns, performance, and production engineering lessons.
2. LinkedIn Post Queue: Exactly ${linkedinCount} authoritative LinkedIn post topic(s) for scheduled days (${linkedinDayLabels}). Focus on engineering leadership insights, system trade-offs, fintech UX reliability, and product-impact lessons.

Return the response in this exact format:
---DEVTO_QUEUE---
1. <DEV.to blog topic 1>
... (exactly ${devtoCount} lines)
---LINKEDIN_QUEUE---
1. <LinkedIn post topic 1>
... (exactly ${linkedinCount} lines)`;

  const aiRes = await generateTextWithFreeAI(systemPrompt, userPrompt, config.textModel, false);
  const raw = aiRes.text;

  let devtoPart = '';
  let linkedinPart = '';

  const devtoSplit = raw.split(/---+DEVTO_QUEUE---+/i)[1] || raw;
  const parts = devtoSplit.split(/---+LINKEDIN_QUEUE---+/i);
  devtoPart = parts[0] || '';
  linkedinPart = parts[1] || '';

  const devtoGenerated =
    target === 'both' || target === 'devto'
      ? parseTopicLines(devtoPart, devtoCount, config.nicheKeywords, 'Deep Dive')
      : config.devtoTopicsQueue;

  const linkedinGenerated =
    target === 'both' || target === 'linkedin'
      ? parseTopicLines(linkedinPart || raw, linkedinCount, config.nicheKeywords, 'Architectural Insight')
      : config.linkedinTopicsQueue;

  const nowIso = new Date().toISOString();
  const updatedConfig = await saveAutomationConfig({
    devtoTopicsQueue: devtoGenerated,
    topicsQueue: devtoGenerated,
    linkedinTopicsQueue: linkedinGenerated,
    lastWeeklyQueueGeneratedWeek: weekKey,
    lastWeeklyQueueGeneratedAt: nowIso,
  });

  await logAutomationStep({
    level: 'success',
    pipeline: 'weekly-queue',
    step: 'WEEKLY_QUEUE_GEN_COMPLETE',
    message: `Generated weekly queues via ${aiRes.modelUsed}: ${devtoGenerated.length} DEV.to topic(s) & ${linkedinGenerated.length} LinkedIn topic(s) for week of ${weekKey}`,
    durationMs: Date.now() - queueStart,
    meta: {
      weekKey,
      modelUsed: aiRes.modelUsed,
      devtoGenerated,
      linkedinGenerated,
    },
  });

  return {
    config: updatedConfig,
    devtoGenerated,
    linkedinGenerated,
    devtoCount,
    linkedinCount,
    weekKey,
    modelUsed: aiRes.modelUsed,
  };
}

/**
 * Ensures the weekly queues for DEV.to and/or LinkedIn are populated for the current week.
 * - At the start of a new week (`lastWeeklyQueueGeneratedWeek !== currentWeekKey`), generates fresh queues for the week based on the scheduled number of days.
 * - If a queue has fulfilled all its cues and is empty, regenerates that queue so the cycle continues uninterrupted.
 */
export async function ensureWeeklyQueuesPopulated(
  target: 'both' | 'devto' | 'linkedin' = 'both',
  now = new Date()
): Promise<AutomationConfig> {
  const config = await getAutomationConfig();
  const currentWeekKey = getStartOfWeekKey(now);
  const isNewWeek = config.lastWeeklyQueueGeneratedWeek !== currentWeekKey;

  const devtoEmpty = !Array.isArray(config.devtoTopicsQueue) || config.devtoTopicsQueue.length === 0;
  const linkedinEmpty =
    !Array.isArray(config.linkedinTopicsQueue) || config.linkedinTopicsQueue.length === 0;

  if (isNewWeek) {
    // Start of a new week: generate fresh queues for both DEV.to and LinkedIn matching their scheduled days
    const generated = await generateWeeklyQueuesWithAI({ target: 'both' });
    return generated.config;
  }

  if (target === 'both' && (devtoEmpty || linkedinEmpty)) {
    const subTarget = devtoEmpty && linkedinEmpty ? 'both' : devtoEmpty ? 'devto' : 'linkedin';
    const generated = await generateWeeklyQueuesWithAI({ target: subTarget });
    return generated.config;
  }

  if (target === 'devto' && devtoEmpty) {
    const generated = await generateWeeklyQueuesWithAI({ target: 'devto' });
    return generated.config;
  }

  if (target === 'linkedin' && linkedinEmpty) {
    const generated = await generateWeeklyQueuesWithAI({ target: 'linkedin' });
    return generated.config;
  }

  return config;
}

