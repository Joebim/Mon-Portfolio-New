export async function updateSocialPost(id: string, patch: Partial<SocialPostRecord>): Promise<SocialPostRecord | null> {
  const db = getFirestoreDb();
  if (db) {
    const ref = db.collection('social_posts').doc(id);
    const snap = await ref.get();
    if (snap.exists) {
      const merged = { ...(snap.data() as SocialPostRecord), ...patch };
      await ref.set(JSON.parse(JSON.stringify(merged)), { merge: true });
      return merged;
    }
  }
  const existing = memorySocialPosts.get(id);
  if (existing) {
    const merged = { ...existing, ...patch };
    memorySocialPosts.set(id, merged);
    return merged;
  }
  return null;
}

