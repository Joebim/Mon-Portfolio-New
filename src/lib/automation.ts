// Free AI Text Generation Engine Loop
// Loops through available AI engines in priority order:
//   1. Google Gemini 2.0 Flash (Free Tier)
//   2. Cloudflare Workers AI (Free Tier — Llama 3.3 70B / Llama 3.1 8B)
//   3. Pollinations OpenAI (100% Free No-Key Fallback)
// If the primary engine fails or hits a rate limit, the loop automatically
// hands over to the next available AI engine.
// ---------------------------------------------------------------------------

type TextEngineId = 'gemini-2.0-flash' | 'cloudflare-workers-ai' | 'pollinations-free';

export async function generateTextWithFreeAI(
  systemPrompt: string,
  userPrompt: string,
  preferredModel: AutomationConfig['textModel'] = 'auto',
  expectJson = false
): Promise<{ text: string; modelUsed: string }> {
  const geminiKey = (process.env.GEMINI_API_KEY || process.env.GOOGLE_GENERATIVE_AI_API_KEY || '').trim();
  const cfAccountId = (process.env.CLOUDFLARE_ACCOUNT_ID || '').trim();
  const cfApiToken = (
    process.env.CLOUDFLARE_API_TOKEN ||
    process.env.CLOUDFLARE_WORKERS_AI_API_KEY ||
    process.env.CLOUDFLARE_API_KEY ||
    ''
  ).trim();
  const cfModel = (
    process.env.CLOUDFLARE_WORKERS_AI_MODEL || '@cf/meta/llama-3.3-70b-instruct-fp8-fast'
  ).trim();

  // Build ordered engine failover list: if a specific engine is preferred, try it first, then loop through the rest
  const defaultOrder: TextEngineId[] = [
    'gemini-2.0-flash',
    'cloudflare-workers-ai',
    'pollinations-free',
  ];
  const engineQueue: TextEngineId[] =
    preferredModel === 'auto'
      ? defaultOrder
      : [
          preferredModel as TextEngineId,
          ...defaultOrder.filter((id) => id !== preferredModel),
        ];

  const startTime = Date.now();

  await logAutomationStep({
    level: 'info',
    pipeline: 'system',
    step: 'AI_ENGINE_LOOP_START',
    message: `Starting AI-Engine Failover Loop: [${engineQueue.join(' → ')}] (preferred=${preferredModel}, geminiConfigured=${Boolean(geminiKey)}, cloudflareWorkersAiConfigured=${Boolean(cfAccountId && cfApiToken)})`,
    meta: {
      preferredModel,
      engineQueue,
      expectJson,
      geminiConfigured: Boolean(geminiKey),
      cloudflareConfigured: Boolean(cfAccountId && cfApiToken),
      cloudflareModel: cfModel,
      systemPromptChars: systemPrompt.length,
      userPromptChars: userPrompt.length,
      userPromptPreview: userPrompt.slice(0, 180),
    },
  });

  for (let i = 0; i < engineQueue.length; i++) {
    const engine = engineQueue[i];
    const nextEngine = engineQueue[i + 1];
    const stepPrefix = `[Engine ${i + 1}/${engineQueue.length}: ${engine}]`;

    // ─────────────────────────────────────────────────────────────────────────
    // ENGINE A: Google Gemini Free Tier (gemini-2.0-flash)
    // ─────────────────────────────────────────────────────────────────────────
    if (engine === 'gemini-2.0-flash') {
      if (!geminiKey) {
        await logAutomationStep({
          level: 'info',
          pipeline: 'system',
          step: 'AI_ENGINE_GEMINI_SKIPPED',
          message: `${stepPrefix} Skipped (GEMINI_API_KEY not set) → handing over to ${nextEngine || 'next engine'}`,
        });
        continue;
      }

      const geminiStart = Date.now();
      try {
        const res = await fetch(
          `https://generativelanguage.googleapis.com/v1beta/models/gemini-2.0-flash:generateContent?key=${geminiKey}`,
          {
            method: 'POST',
            headers: { 'Content-Type': 'application/json' },
            body: JSON.stringify({
              systemInstruction: { parts: [{ text: systemPrompt }] },
              contents: [{ role: 'user', parts: [{ text: userPrompt }] }],
              generationConfig: {
                temperature: 0.75,
                maxOutputTokens: 8192,
                ...(expectJson ? { responseMimeType: 'application/json' } : {}),
              },
            }),
            signal: AbortSignal.timeout(45000),
          }
        );

        if (res.ok) {
          const data = await res.json();
          const text = data?.candidates?.[0]?.content?.parts?.[0]?.text;
          const finishReason = data?.candidates?.[0]?.finishReason;
          if (text) {
            await logAutomationStep({
              level: 'success',
              pipeline: 'system',
              step: 'AI_ENGINE_GEMINI_OK',
              message: `${stepPrefix} Gemini 2.0 Flash succeeded with ${text.length} chars (finishReason=${finishReason || 'STOP'})`,
              durationMs: Date.now() - geminiStart,
              meta: {
                engine,
                chars: text.length,
                finishReason,
                preview: text.slice(0, 200),
              },
            });
            return { text: text.trim(), modelUsed: 'gemini-2.0-flash (Free Tier)' };
          }
        } else {
          const errBody = await res.text().catch(() => '');
          await logAutomationStep({
            level: 'warn',
            pipeline: 'system',
            step: 'AI_ENGINE_GEMINI_FAILOVER',
            message: `${stepPrefix} Gemini HTTP ${res.status} — failing over to ${nextEngine || 'next engine'}`,
            durationMs: Date.now() - geminiStart,
            meta: { status: res.status, nextEngine, errorBody: errBody.slice(0, 300) },
          });
        }
      } catch (err) {
        await logAutomationStep({
          level: 'warn',
          pipeline: 'system',
          step: 'AI_ENGINE_GEMINI_FAILOVER',
          message: `${stepPrefix} Gemini exception — failing over to ${nextEngine || 'next engine'}: ${err instanceof Error ? err.message : String(err)}`,
          durationMs: Date.now() - geminiStart,
        });
      }
      continue;
    }

    // ─────────────────────────────────────────────────────────────────────────
    // ENGINE B: Cloudflare Workers AI (Takes over when Gemini fails!)
    // ─────────────────────────────────────────────────────────────────────────
    if (engine === 'cloudflare-workers-ai') {
      if (!cfAccountId || !cfApiToken) {
        await logAutomationStep({
          level: 'info',
          pipeline: 'system',
          step: 'AI_ENGINE_CLOUDFLARE_SKIPPED',
          message: `${stepPrefix} Skipped (CLOUDFLARE_ACCOUNT_ID or CLOUDFLARE_API_TOKEN not set in .env.local) → handing over to ${nextEngine || 'next engine'}`,
        });
        continue;
      }

      const cfModelsToTry = Array.from(
        new Set([cfModel, '@cf/meta/llama-3.3-70b-instruct-fp8-fast', '@cf/meta/llama-3.1-8b-instruct'])
      );

      for (const activeCfModel of cfModelsToTry) {
        const cfStart = Date.now();
        try {
          // Cloudflare Workers AI OpenAI-compatible Chat Completions endpoint
          const res = await fetch(
            `https://api.cloudflare.com/client/v4/accounts/${cfAccountId}/ai/v1/chat/completions`,
            {
              method: 'POST',
              headers: {
                'Content-Type': 'application/json',
                Authorization: `Bearer ${cfApiToken}`,
              },
              body: JSON.stringify({
                model: activeCfModel,
                messages: [
                  { role: 'system', content: systemPrompt },
                  { role: 'user', content: userPrompt },
                ],
                temperature: 0.75,
                max_tokens: 4096,
                ...(expectJson ? { response_format: { type: 'json_object' } } : {}),
              }),
              signal: AbortSignal.timeout(50000),
            }
          );

          if (res.ok) {
            const data = await res.json();
            const text =
              data?.choices?.[0]?.message?.content ||
              data?.result?.response ||
              data?.result?.choices?.[0]?.message?.content;

            if (text && typeof text === 'string') {
              await logAutomationStep({
                level: 'success',
                pipeline: 'system',
                step: 'AI_ENGINE_CLOUDFLARE_OK',
                message: `${stepPrefix} Cloudflare Workers AI (${activeCfModel}) succeeded with ${text.length} chars`,
                durationMs: Date.now() - cfStart,
                meta: {
                  engine,
                  model: activeCfModel,
                  chars: text.length,
                  preview: text.slice(0, 200),
                },
              });
              return {
                text: text.trim(),
                modelUsed: `cloudflare-workers-ai (${activeCfModel})`,
              };
            }
          } else {
            const errBody = await res.text().catch(() => '');
            await logAutomationStep({
              level: 'warn',
              pipeline: 'system',
              step: 'AI_ENGINE_CLOUDFLARE_MODEL_WARN',
              message: `${stepPrefix} Cloudflare Workers AI (${activeCfModel}) HTTP ${res.status}`,
              durationMs: Date.now() - cfStart,
              meta: { model: activeCfModel, status: res.status, errorBody: errBody.slice(0, 300) },
            });
          }
        } catch (err) {
          await logAutomationStep({
            level: 'warn',
            pipeline: 'system',
            step: 'AI_ENGINE_CLOUDFLARE_FAILOVER',
            message: `${stepPrefix} Cloudflare Workers AI (${activeCfModel}) exception: ${err instanceof Error ? err.message : String(err)}`,
            durationMs: Date.now() - cfStart,
          });
        }
      }
      continue;
    }

    // ─────────────────────────────────────────────────────────────────────────
    // ENGINE C: Pollinations.ai OpenAI-compatible Free Endpoint (Zero API Key)
    // ─────────────────────────────────────────────────────────────────────────
    if (engine === 'pollinations-free') {
      const pollStart = Date.now();
      try {
        const res = await fetch('https://text.pollinations.ai/openai', {
          method: 'POST',
          headers: { 'Content-Type': 'application/json' },
          body: JSON.stringify({
            model: 'openai',
            messages: [
              { role: 'system', content: systemPrompt },
              { role: 'user', content: userPrompt },
            ],
            temperature: 0.75,
            max_tokens: 4096,
            ...(expectJson ? { response_format: { type: 'json_object' } } : {}),
          }),
          signal: AbortSignal.timeout(50000),
        });

        if (res.ok) {
          const data = await res.json();
          const text = data?.choices?.[0]?.message?.content;
          const finishReason = data?.choices?.[0]?.finish_reason;
          if (text) {
            await logAutomationStep({
              level: 'success',
              pipeline: 'system',
              step: 'AI_ENGINE_POLLINATIONS_OK',
              message: `${stepPrefix} Pollinations OpenAI succeeded with ${text.length} chars (finishReason=${finishReason || 'stop'})`,
              durationMs: Date.now() - pollStart,
              meta: {
                engine,
                chars: text.length,
                finishReason,
                preview: text.slice(0, 200),
              },
            });
            return { text: text.trim(), modelUsed: 'pollinations-openai (100% Free No-Key)' };
          }
        } else {
          const errBody = await res.text().catch(() => '');
          await logAutomationStep({
            level: 'warn',
            pipeline: 'system',
            step: 'AI_ENGINE_POLLINATIONS_HTTP_WARN',
            message: `${stepPrefix} Pollinations OpenAI HTTP ${res.status}`,
            durationMs: Date.now() - pollStart,
            meta: { status: res.status, errorBody: errBody.slice(0, 300) },
          });
        }
      } catch (err) {
        await logAutomationStep({
          level: 'warn',
          pipeline: 'system',
          step: 'AI_ENGINE_POLLINATIONS_ERR',
          message: `${stepPrefix} Pollinations OpenAI failed: ${err instanceof Error ? err.message : String(err)}`,
          durationMs: Date.now() - pollStart,
        });
      }
      continue;
    }
  }

  await logAutomationStep({
    level: 'error',
    pipeline: 'system',
    step: 'AI_ENGINE_LOOP_EXHAUSTED',
    message: `All AI engines in loop [${engineQueue.join(' → ')}] failed or timed out.`,
    durationMs: Date.now() - startTime,
  });

  throw new Error(
    'All AI text engines (Gemini 2.0 Flash, Cloudflare Workers AI, Pollinations) timed out or failed. Check internet connection or verify GEMINI_API_KEY / CLOUDFLARE_API_TOKEN in .env.local.'
  );
}

